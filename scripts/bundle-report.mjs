import {readFile,writeFile,mkdir} from 'node:fs/promises';
const parts = ['lib/model.mjs','lib/import-matrix.mjs','lib/report-csv.mjs','supabase/functions/report-inbox/index.ts'];
let out = '// Generated by scripts/bundle-report.mjs. Deploy as report-inbox.\n';
for(const path of parts) out += '\n' + (await readFile(path,'utf8')).replace(/^import .* from ['"]\..*;\n/gm,'').replace(/^export /gm,'');
await mkdir('supabase/bundles',{recursive:true});await writeFile('supabase/bundles/report-inbox.ts',out);
